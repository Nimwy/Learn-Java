-- V1: Tạo bảng sessions (lưu refresh token) — chuyển từ bài 9 sang Flyway quản lý.
-- Trước đây Hibernate tự tạo bảng này bằng ddl-auto=create. Giờ Flyway tạo, có lịch sử rõ ràng.
--
-- Quy ước tên file:  V<số>__<mô tả>.sql   (hai dấu gạch dưới)
-- Flyway chạy theo thứ tự số version, mỗi file chỉ chạy MỘT lần và ghi lại vào bảng
-- flyway_schema_history. Lần chạy sau thấy đã chạy rồi thì bỏ qua.

CREATE TABLE sessions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email       VARCHAR(255) NOT NULL,
    token_hash  VARCHAR(255) NOT NULL UNIQUE,
    expires_at  TIMESTAMP    NOT NULL
);

-- Ghi chú: ràng buộc UNIQUE ở trên đã tự tạo một index cho token_hash,
-- nên việc tra cứu phiên theo token_hash (đăng nhập/refresh) vẫn nhanh.
